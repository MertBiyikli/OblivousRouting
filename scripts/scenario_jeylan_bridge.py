"""Trusted bridge from Jeylan's model-facing tool to persisted E-Routing analysis."""
from __future__ import annotations

from dataclasses import dataclass
from uuid import uuid4
from typing import Any

from scenario_runtime import ScenarioRequest, TrustedRun, execute


@dataclass(frozen=True)
class ScenarioBridge:
    trusted: TrustedRun

    def evaluate(self, arguments: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(arguments, dict) or set(arguments) != {'demand_model', 'include_layer1', 'demand_scale', 'capacity_upgrades'}:
            raise ValueError('Expected demand_model, include_layer1, demand_scale and capacity_upgrades')
        # Scenario ID is generated by trusted code, never by the model.
        request = ScenarioRequest.from_dict({
            'scenario_id': f'jeylan-{uuid4().hex}',
            'scenario_type': 'capacity_planning',
            'demand_model': arguments['demand_model'],
            'include_layer1': arguments['include_layer1'],
            'demand_scale': arguments['demand_scale'],
            'capacity_upgrades': arguments['capacity_upgrades'],
        })
        result = execute(request, self.trusted)
        if result.get('status') != 'completed' or result.get('execution_mode') != 'persisted_routing_scheme':
            raise ValueError('Unexpected scenario result status or execution mode')
        metrics = result.get('metrics')
        if not isinstance(metrics, dict) or not isinstance(metrics.get('congestion'), (float, int)) or isinstance(metrics.get('congestion'), bool):
            raise ValueError('Missing congestion evidence')
        if arguments['include_layer1'] and not isinstance(metrics.get('layer1'), dict):
            raise ValueError('Missing requested Layer-1 evidence')
        return result
