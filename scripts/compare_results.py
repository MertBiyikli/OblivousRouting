#!/usr/bin/env python3

import argparse
import csv
from collections import defaultdict
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser(
        description="Compare E-Routing solver experiment results."
    )

    parser.add_argument(
        "--input",
        required=True,
        help="Path to summary.csv generated by run_experiments.py.",
    )

    parser.add_argument(
        "--output",
        default=None,
        help=(
            "Output comparison CSV. "
            "Defaults to comparison.csv next to summary.csv."
        ),
    )

    return parser.parse_args()


def as_float(value):
    if value is None or value == "":
        return None

    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def rank_rows(rows, field):
    """
    Rank rows by ascending numeric value.

    Smaller is considered better for:
      - congestion
      - oblivious ratio
      - runtime
    """

    valid = [
        row
        for row in rows
        if as_float(row.get(field)) is not None
    ]

    valid.sort(
        key=lambda row: as_float(row[field])
    )

    ranks = {}

    for index, row in enumerate(valid, start=1):
        ranks[id(row)] = index

    return ranks


def relative_to_best(value, best):
    """
    Return multiplicative factor relative to best.

    Example:
        value = 120
        best  = 100

        -> 1.20
    """

    value = as_float(value)
    best = as_float(best)

    if value is None or best is None:
        return None

    if best == 0:
        return None

    return value / best


def format_number(value, digits=6):
    if value is None:
        return ""

    return f"{value:.{digits}g}"


def main():
    args = parse_args()

    input_path = Path(args.input)

    if not input_path.exists():
        raise SystemExit(
            f"Input file does not exist: {input_path}"
        )

    output_path = (
        Path(args.output)
        if args.output
        else input_path.parent / "comparison.csv"
    )

    # --------------------------------------------------------------
    # Read normalized experiment summary
    # --------------------------------------------------------------

    with input_path.open(newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    if not rows:
        raise SystemExit(
            f"No experiment rows found in {input_path}"
        )

    # --------------------------------------------------------------
    # Group by graph + demand model
    #
    # We compare solvers only when they were evaluated on the same
    # graph and demand model.
    # --------------------------------------------------------------

    groups = defaultdict(list)

    for row in rows:
        key = (
            row.get("graph"),
            row.get("demand_model"),
        )

        groups[key].append(row)

    comparison_rows = []

    # --------------------------------------------------------------
    # Compare every solver within each experiment group
    # --------------------------------------------------------------

    for (graph, demand_model), group_rows in groups.items():

        congestion_values = [
            as_float(row.get("congestion"))
            for row in group_rows
        ]

        congestion_values = [
            value
            for value in congestion_values
            if value is not None
        ]

        runtime_values = [
            as_float(
                row.get("total_runtime_microseconds")
            )
            for row in group_rows
        ]

        runtime_values = [
            value
            for value in runtime_values
            if value is not None
        ]

        ratio_values = [
            as_float(row.get("oblivious_ratio"))
            for row in group_rows
        ]

        ratio_values = [
            value
            for value in ratio_values
            if value is not None
        ]

        best_congestion = (
            min(congestion_values)
            if congestion_values
            else None
        )

        fastest_runtime = (
            min(runtime_values)
            if runtime_values
            else None
        )

        best_oblivious_ratio = (
            min(ratio_values)
            if ratio_values
            else None
        )

        congestion_ranks = rank_rows(
            group_rows,
            "congestion"
        )

        runtime_ranks = rank_rows(
            group_rows,
            "total_runtime_microseconds"
        )

        ratio_ranks = rank_rows(
            group_rows,
            "oblivious_ratio"
        )

        for row in group_rows:

            congestion = as_float(
                row.get("congestion")
            )

            runtime = as_float(
                row.get(
                    "total_runtime_microseconds"
                )
            )

            oblivious_ratio = as_float(
                row.get("oblivious_ratio")
            )

            congestion_factor = relative_to_best(
                congestion,
                best_congestion
            )

            runtime_factor = relative_to_best(
                runtime,
                fastest_runtime
            )

            ratio_factor = relative_to_best(
                oblivious_ratio,
                best_oblivious_ratio
            )

            # ------------------------------------------------------
            # Simple balanced comparison score
            #
            # 1.0 = best possible if a solver is best in both
            # congestion and runtime.
            #
            # Lower is better.
            #
            # This is deliberately simple and transparent.
            # ------------------------------------------------------

            score_components = []

            if congestion_factor is not None:
                score_components.append(
                    congestion_factor
                )

            if runtime_factor is not None:
                score_components.append(
                    runtime_factor
                )

            comparison_score = (
                sum(score_components)
                / len(score_components)
                if score_components
                else None
            )

            comparison_rows.append({

                # --------------------------------------------------
                # Experiment identity
                # --------------------------------------------------

                "graph":
                    graph,

                "demand_model":
                    demand_model,

                "solver":
                    row.get("solver"),

                "solver_type":
                    row.get("solver_type"),

                "status":
                    row.get("status"),

                # --------------------------------------------------
                # Raw metrics
                # --------------------------------------------------

                "congestion":
                    row.get("congestion"),

                "oblivious_ratio":
                    row.get("oblivious_ratio"),

                "total_runtime_microseconds":
                    row.get(
                        "total_runtime_microseconds"
                    ),

                # --------------------------------------------------
                # Rankings
                # --------------------------------------------------

                "congestion_rank":
                    congestion_ranks.get(
                        id(row),
                        ""
                    ),

                "oblivious_ratio_rank":
                    ratio_ranks.get(
                        id(row),
                        ""
                    ),

                "runtime_rank":
                    runtime_ranks.get(
                        id(row),
                        ""
                    ),

                # --------------------------------------------------
                # Relative performance
                # --------------------------------------------------

                "congestion_vs_best":
                    format_number(
                        congestion_factor
                    ),

                "oblivious_ratio_vs_best":
                    format_number(
                        ratio_factor
                    ),

                "runtime_vs_fastest":
                    format_number(
                        runtime_factor
                    ),

                # --------------------------------------------------
                # Combined indicator
                # --------------------------------------------------

                "comparison_score":
                    format_number(
                        comparison_score
                    ),

                # --------------------------------------------------
                # Context
                # --------------------------------------------------

                "nodes":
                    row.get("nodes"),

                "edges":
                    row.get("edges"),

                "threads":
                    row.get("threads"),

                "seed":
                    row.get("seed"),

                "source_json":
                    row.get("json_file"),
            })

    # --------------------------------------------------------------
    # Sort output:
    #
    # graph
    # -> demand model
    # -> comparison score
    # --------------------------------------------------------------

    def sort_key(row):
        score = as_float(
            row.get("comparison_score")
        )

        if score is None:
            score = float("inf")

        return (
            row.get("graph") or "",
            row.get("demand_model") or "",
            score,
        )

    comparison_rows.sort(
        key=sort_key
    )

    # --------------------------------------------------------------
    # Write comparison.csv
    # --------------------------------------------------------------

    fieldnames = [
        "graph",
        "demand_model",

        "solver",
        "solver_type",
        "status",

        "congestion",
        "congestion_rank",
        "congestion_vs_best",

        "oblivious_ratio",
        "oblivious_ratio_rank",
        "oblivious_ratio_vs_best",

        "total_runtime_microseconds",
        "runtime_rank",
        "runtime_vs_fastest",

        "comparison_score",

        "nodes",
        "edges",
        "threads",
        "seed",

        "source_json",
    ]

    with output_path.open(
            "w",
            newline=""
    ) as f:

        writer = csv.DictWriter(
            f,
            fieldnames=fieldnames
        )

        writer.writeheader()

        writer.writerows(
            comparison_rows
        )

    # --------------------------------------------------------------
    # Console report
    # --------------------------------------------------------------

    print()
    print(
        f"Input:      {input_path}"
    )

    print(
        f"Comparison: {output_path}"
    )

    print(
        f"Rows:       {len(comparison_rows)}"
    )

    print()

    for key in sorted(groups):
        graph, demand_model = key

        group = [
            row
            for row in comparison_rows
            if (
                    row["graph"] == graph
                    and
                    row["demand_model"] == demand_model
            )
        ]

        group.sort(
            key=lambda row:
            as_float(
                row["comparison_score"]
            )
            if row["comparison_score"]
            else float("inf")
        )

        print(
            f"{graph} | {demand_model}"
        )

        for row in group:

            solver_type = (
                    row["solver_type"]
                    or row["solver"]
                    or "unknown"
            )

            print(
                f"  {solver_type:30} "
                f"congestion={row['congestion']:>12} "
                f"runtime={row['total_runtime_microseconds']:>12} us "
                f"score={row['comparison_score']}"
            )

        print()


if __name__ == "__main__":
    main()
